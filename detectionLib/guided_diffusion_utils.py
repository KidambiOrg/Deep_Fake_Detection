"""
Guided Diffusion Utilities for DistilDIRE

This module contains the essential guided diffusion components needed for DistilDIRE
to perform DDIM inversion and epsilon computation.

Based on: https://github.com/miraflow/DistilDIRE
"""

import torch
import torch.nn as nn
import torch.nn.functional as F
import numpy as np
import math
from typing import Optional, Union, Tuple
from enum import Enum

class ModelMeanType(Enum):
    """
    Which type of output the model predicts.
    """
    PREVIOUS_X = "previous_x"  # the model predicts x_{t-1}
    START_X = "start_x"  # the model predicts x_0
    EPSILON = "epsilon"  # the model predicts epsilon


class ModelVarType(Enum):
    """
    What is used as the model's output variance.
    """
    LEARNED = "learned"
    LEARNED_RANGE = "learned_range"
    FIXED_SMALL = "fixed_small"
    FIXED_LARGE = "fixed_large"


class LossType(Enum):
    """
    Which loss function to use for the diffusion loss.
    """
    MSE = "mse"  # use raw MSE loss (and KL when learning variances)
    RESCALED_MSE = "rescaled_mse"  # rescale to avoid instability
    KL = "kl"  # use the variational lower-bound
    RESCALED_KL = "rescaled_kl"  # like KL, but rescale to avoid instability


def mean_flat(tensor):
    """
    Take the mean over all non-batch dimensions.
    """
    return tensor.mean(dim=list(range(1, len(tensor.shape))))


def _extract_into_tensor(arr, timesteps, broadcast_shape):
    """
    Extract values from a 1-D numpy array for a batch of indices.
    """
    res = torch.from_numpy(arr).to(device=timesteps.device)[timesteps].float()
    while len(res.shape) < len(broadcast_shape):
        res = res[..., None]
    return res.expand(broadcast_shape)


